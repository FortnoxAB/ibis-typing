from __future__ import annotations

import datetime
import decimal
import uuid
from typing import Any, cast, overload

from ibis import Table, Value, ir
from typing_extensions import TypeForm

from . import ibis_types as it
from .extension_method import Deferred

# Typed token for chaining instance methods after extension methods.
deferred = cast(Table, Deferred())
defer_val = cast(Value, Deferred())


# Ibis value types
@overload
def defer[T: ir.Value](type_: type[T]) -> T: ...
# Primitives
@overload
def defer(type_: type[bool]) -> ir.BooleanValue: ...
@overload
def defer(type_: type[int]) -> ir.IntegerValue: ...
@overload
def defer(type_: type[float]) -> ir.FloatingValue: ...
@overload
def defer(type_: type[bytes]) -> ir.BinaryValue: ...
@overload
def defer(type_: type[str]) -> ir.StringValue: ...
# Complex types
@overload
def defer(type_: type[datetime.datetime]) -> ir.TimestampValue: ...
@overload
def defer(type_: type[datetime.date]) -> ir.DateValue: ...
@overload
def defer(type_: type[datetime.time]) -> ir.TimeValue: ...
@overload
def defer(type_: type[decimal.Decimal]) -> ir.DecimalValue: ...
@overload
def defer(type_: type[uuid.UUID]) -> ir.UUIDValue: ...
# Collection types
@overload
def defer(type_: type[dict[Any, Any]]) -> ir.MapValue: ...
@overload
def defer(type_: type[list[Any]]) -> ir.ArrayValue: ...
# IbisSchema type aliases are type forms rather than classes.
# Order matters: an alias matches the first overload containing all its members.
# Primitives: Boolean before Integer, Integer before Floating (int promotes to float).
@overload
def defer(type_: TypeForm[it.Boolean]) -> ir.BooleanValue: ...
@overload
def defer(type_: TypeForm[it.Integer]) -> ir.IntegerValue: ...
@overload
def defer(type_: TypeForm[it.Floating]) -> ir.FloatingValue: ...
@overload
def defer(type_: TypeForm[it.Binary]) -> ir.BinaryValue: ...
@overload
def defer(type_: TypeForm[it.String]) -> ir.StringValue: ...
# Complex types: Timestamp before Date (datetime is a date).
@overload
def defer(type_: TypeForm[it.Timestamp]) -> ir.TimestampValue: ...
@overload
def defer(type_: TypeForm[it.Date]) -> ir.DateValue: ...
@overload
def defer(type_: TypeForm[it.Time]) -> ir.TimeValue: ...
@overload
def defer(type_: TypeForm[it.Decimal]) -> ir.DecimalValue: ...
@overload
def defer(type_: TypeForm[it.UUID]) -> ir.UUIDValue: ...
# Collections: after String and Binary, which are sequences too.
@overload
def defer(type_: TypeForm[it.Struct[Any]]) -> ir.StructValue: ...
@overload
def defer(type_: TypeForm[it.Array[Any]]) -> ir.ArrayValue: ...
@overload
def defer(type_: TypeForm[it.Map[Any, Any]]) -> ir.MapValue: ...
# JSON wildcard
@overload
def defer(type_: TypeForm[it.JSON]) -> ir.JSONValue: ...
@overload
def defer(type_: Any = None) -> ir.Value: ...
def defer(type_: Any = None) -> Any:
    return Deferred()
